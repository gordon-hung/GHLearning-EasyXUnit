namespace GHLearning.EasyXUnit.Core;

public class CalculatorUtensil
{
	public static int Plus(int numberOne, int numberTwo)
		=> numberOne + numberTwo;

	public static decimal Plus(decimal numberOne, decimal numberTwo)
		=> numberOne + numberTwo;

	public static int Minus(int numberOne, int numberTwo)
		=> numberOne - numberTwo;

	public static decimal Minus(decimal numberOne, decimal numberTwo)
		=> numberOne - numberTwo;
}
